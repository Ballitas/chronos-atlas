export function resolveTheme(themeKey?: string | null, customOverride?: Partial<ThemeConfig> | null): ThemeConfig {
  const base = (themeKey && TOPIC_THEMES[themeKey]) || DEFAULT_THEME;
  if (!customOverride) return base;
  return {
    ...base,
    ...Object.fromEntries(
      Object.entries(customOverride).filter(([, value]) => value !== undefined && value !== null && value !== '')
    ),
  } as ThemeConfig;
}
